# У Python немає перевантаження функцій, у той же час немає помилки
# Переозначення. Оголошення функції ближче до операції присвоєння:
# повторне оголошення переприсвоює тіло функції незалежно від кількості/типів
# їх параметрів. Тому традиційно функції широкого призначення мають
# велику кількість параметрів за замовчанням.

# чи можлива рекурсія?
def factorial(n: int) -> int:    # n! = 1*2*3*...*n = n*(n-1)!
    # 1 вихід за умови досягнення певних значень
    if n <= 1:
        return 1

    # 2 виклик цієї ж функції зі зміненим аргументом
    return n * factorial(n - 1)

# Алгоритм Евкліда для пошуку найбільшого спільного дільника
# двох чисел A і B: якщо A і B мають спільний дільник, то
# залишок ділення A і B також ділиться на цей дільник.
# gcd(a, b) = gcd(b, a % b) якщо a < b, інакше = gcd(b, a)
def gcd(a: int, b: int) -> int:
    if a < b:
        return gcd(b, a)
    elif b == 0:
        return a
    else:
        return gcd(b, a % b)

